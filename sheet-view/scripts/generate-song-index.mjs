/**
 * Regenerates `song-book/README.md` — a markdown table of every ChordPro chart
 * in `song-book/`, with title/artist pulled from each file's `{t:}`/`{title:}`
 * and `{artist:}` directives, linking to the raw `.cho` file and to the
 * hosted Sheet-View viewer.
 *
 * Run after adding, renaming, or removing a chart:
 *
 *   bun run generate:songbook          # or: bun scripts/generate-song-index.mjs
 *
 * Plain node:fs — no imports from src/, so `node` works too, not just `bun`.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const SONG_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '../../song-book')
const OUT = resolve(SONG_DIR, 'README.md')
const VIEW_BASE =
  'https://mdprewitt.github.io/music/?view=https://github.com/mdprewitt/music/blob/main/song-book/'

// Matches a directive on its own line: {t:...}, {title:...}, or {artist:...}.
// Only the first occurrence of each tag in a file is used (ChordPro files here
// never repeat one), so a later {t:} for a second song in the same file (none
// exist today) is ignored rather than producing a bogus extra row.
const DIRECTIVE = /^\s*\{\s*(title|t|artist)\s*:\s*([^}]*)\}\s*$/im

function readTag(text, names) {
  for (const line of text.split('\n')) {
    const m = DIRECTIVE.exec(line)
    if (m && names.includes(m[1].toLowerCase())) return m[2].trim()
  }
  return ''
}

// Escape markdown table-breaking characters so a stray '|' in a title/artist
// can't corrupt the row.
function escapeCell(s) {
  return s.replace(/\\/g, '\\\\').replace(/\|/g, '\\|')
}

const files = readdirSync(SONG_DIR)
  .filter((f) => f.toLowerCase().endsWith('.cho'))
  .sort()

if (files.length === 0) {
  console.error(`no .cho files found in ${SONG_DIR} — refusing to overwrite ${OUT}`)
  process.exit(1)
}

const rows = files.map((file) => {
  const text = readFileSync(resolve(SONG_DIR, file), 'utf8')
  const title = readTag(text, ['t', 'title']) || file.replace(/\.cho$/i, '')
  const artist = readTag(text, ['artist'])
  const chordproUrl = VIEW_BASE + encodeURIComponent(file)
  const links = `[CHO](${encodeURIComponent(file)}) [Song-View](${chordproUrl})`
  return { title, artist, file, links }
})

rows.sort((a, b) => a.title.localeCompare(b.title, undefined, { sensitivity: 'base' }))

const tableRows = rows
  .map((r) => `| ${escapeCell(r.title)} | ${escapeCell(r.artist)} | ${r.links} |`)
  .join('\n')

const body = `<!-- GENERATED by sheet-view/scripts/generate-song-index.mjs — do not edit by hand. -->

# Song Book

${rows.length} ChordPro charts. Run \`bun run generate:songbook\` from \`sheet-view/\` after adding a chart.

| Song | Artist | Links |
| --- | --- | --- |
${tableRows}
`

writeFileSync(OUT, body)
console.log(`wrote ${rows.length} songs to ${OUT}`)
