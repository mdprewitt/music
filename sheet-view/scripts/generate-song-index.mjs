/**
 * Regenerates the song index from every ChordPro chart in `song-book/`, with
 * title/artist pulled from each file's `{t:}`/`{title:}` and `{artist:}`
 * directives. Two outputs, both linking to the raw `.cho` file and to the
 * hosted Sheet-View viewer:
 *
 *   - `song-book/README.md`    — markdown table, browsable on github.com
 *   - `public/songbook.html`   — standalone page, deployed to GitHub Pages
 *     alongside the app (public/ is copied into dist/ verbatim by Vite —
 *     see the relative-URL note below)
 *
 * Run after adding, renaming, or removing a chart:
 *
 *   bun run generate:songbook          # or: bun scripts/generate-song-index.mjs
 *
 * Plain node:fs — no imports from src/, so `node` works too, not just `bun`.
 * The GitHub Pages workflow (.github/workflows/pages.yml) also runs this
 * before every build, so a forgotten local run can't ship a stale page —
 * but commit both generated files anyway, so `bun dev`/`preview` and the e2e
 * suite see a current songbook.html without needing a build step first.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SONG_DIR = resolve(ROOT, '../song-book')
const OUT_MD = resolve(SONG_DIR, 'README.md')
const OUT_HTML = resolve(ROOT, 'public/songbook.html')
const BLOB_BASE = 'https://github.com/mdprewitt/music/blob/main/song-book/'
const VIEW_BASE = 'https://mdprewitt.github.io/music/?view=' + BLOB_BASE

// Matches a directive on its own line: {t:...}, {title:...}, or {artist:...}.
// Only the first occurrence of each tag in a file is used (ChordPro files here
// never repeat one), so a later {t:} for a second song in the same file (none
// exist today) is ignored rather than producing a bogus extra row.
const DIRECTIVE = /^\s*\{\s*(title|t|artist)\s*:\s*([^}]*)\}\s*$/im

function readTag(text, names) {
  for (const line of text.split('\n')) {
    const m = DIRECTIVE.exec(line)
    if (m && names.includes(m[1].toLowerCase())) return m[2].trim()
  }
  return ''
}

// Escape markdown table-breaking characters so a stray '|' in a title/artist
// can't corrupt the row.
function escapeCell(s) {
  return s.replace(/\\/g, '\\\\').replace(/\|/g, '\\|')
}

function escapeHtml(s) {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

const files = readdirSync(SONG_DIR)
  .filter((f) => f.toLowerCase().endsWith('.cho'))
  .sort()

if (files.length === 0) {
  console.error(`no .cho files found in ${SONG_DIR} — refusing to overwrite the index`)
  process.exit(1)
}

const rows = files.map((file) => {
  const text = readFileSync(resolve(SONG_DIR, file), 'utf8')
  const title = readTag(text, ['t', 'title']) || file.replace(/\.cho$/i, '')
  const artist = readTag(text, ['artist'])
  return { title, artist, file }
})

rows.sort((a, b) => a.title.localeCompare(b.title, undefined, { sensitivity: 'base' }))

// ---- song-book/README.md -------------------------------------------------

const tableRowsMd = rows
  .map((r) => {
    const chordproUrl = VIEW_BASE + encodeURIComponent(r.file)
    const links = `[CHO](${encodeURIComponent(r.file)}) [Song-View](${chordproUrl})`
    return `| ${escapeCell(r.title)} | ${escapeCell(r.artist)} | ${links} |`
  })
  .join('\n')

const bodyMd = `<!-- GENERATED by sheet-view/scripts/generate-song-index.mjs — do not edit by hand. -->

# Song Book

${rows.length} ChordPro charts. Run \`bun run generate:songbook\` from \`sheet-view/\` after adding a chart.

| Song | Artist | Links |
| --- | --- | --- |
${tableRowsMd}
`

writeFileSync(OUT_MD, bodyMd)

// ---- public/songbook.html -------------------------------------------------
//
// public/ is copied into dist/ verbatim by Vite — unlike index.html it does
// NOT rewrite root-relative URLs for the project-page base (BASE_PATH=/music/
// in CI). So every same-site link here is relative ('./…'), never '/…'.

const tableRowsHtml = rows
  .map((r) => {
    const sourceHref = BLOB_BASE + encodeURIComponent(r.file)
    const viewerHref = './?view=' + sourceHref
    const search = escapeHtml(`${r.title} ${r.artist}`.toLowerCase())
    return `        <tr data-search="${search}">
          <td><a href="${viewerHref}">${escapeHtml(r.title)}</a></td>
          <td>${escapeHtml(r.artist)}</td>
          <td><a href="${sourceHref}">.cho</a></td>
        </tr>`
  })
  .join('\n')

